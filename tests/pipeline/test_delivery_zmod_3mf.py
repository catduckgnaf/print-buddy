def test_problems_flag_a_plate_md5_that_does_not_match_the_inner_gcode(tmp_path):
    package = orca_export(tmp_path / "plate_1.gcode.3mf", RAW.encode())
    rewrite_entry(package, "Metadata/plate_1.gcode.md5", b"0" * 32)
    model, adapter = ad5x()
    problems = delivery.zmod_package_problems(package, model, adapter)
    assert any("plate_1.gcode.md5 does not match" in p for p in problems), problems


