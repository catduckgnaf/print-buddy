"""ZMod .gcode.3mf delivery packages (#564 stage 1): the Orca sliced export, Print Handy's
finalize repack, and the validation a package must pass before a job may record it.

The package contract is the one ZMod 1.7.5's own readers enforce (Stage 0 of #564 ran
ghzserg's ThreeMFParser and Klipper-side get_colors against real packages): one sliced
plate, the plate MD5 entry equal to the inner G-code's upper-case MD5, slice_info.config
filaments with type and colour, plate_1.json bbox_all, thumbnails. The fixtures below
mirror the layout the pinned OrcaSlicer (v2.5.0-alpha) CLI export actually writes.
"""
import copy
import hashlib
import io
import json
import zipfile
from pathlib import Path

import pytest
from PIL import Image

from print_handy import printers, settings
from print_handy.core import delivery

RAW = (
    "; generated by OrcaSlicer 2.5.0-alpha\n"
    "; HEADER_BLOCK_START\n"
    "; filament_type = PLA;PLA\n"
    "; filament_colour = #FF0000;#0000FF\n"
    "; nozzle_diameter = 0.4\n"
    "; estimated printing time (normal mode) = 1h 2m 3s\n"
    "; total filament used [g] = 12.34\n"
    "; HEADER_BLOCK_END\n"
    "M190 S60\nM104 S210 T0\n"
    "START_PRINT BED_TEMP=60 EXTRUDER_TEMP=210 MESH=auto\n"
    "G1 X10 Y10 Z0.2 E1.0\nT1\nG1 X20 Y20 E2.0\nM400\nEND_PRINT\n"
)


def finalized(raw=RAW):
    """The same bytes after Print Handy's ZMod finalize: colour data lines + MD5 header."""
    payload = raw + "; zmod_color_data = 0|#FF0000|PLA\n; zmod_color_data = 1|#0000FF|PLA\n"
    return "; MD5:" + hashlib.md5(payload.encode()).hexdigest() + "\r\n" + payload


def _png(rgb):
    buf = io.BytesIO()
    Image.new("RGB", (512, 512), rgb).save(buf, "PNG")
    return buf.getvalue()


def slice_info(filaments=(("PLA", "#FF0000", "8.0"), ("PLA", "#0000FF", "4.34")), model_id=""):
    rows = "".join(
        f'  <filament id="{i}" type="{t}" color="{c}" used_g="{g}"/>\n'
        for i, (t, c, g) in enumerate(filaments, 1))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<config>\n <header>\n'
            '  <header_item key="X-BBL-Client-Type" value="slicer"/>\n </header>\n <plate>\n'
            '  <metadata key="index" value="1"/>\n'
            '  <metadata key="prediction" value="3723"/>\n'
            '  <metadata key="weight" value="12.34"/>\n'
            f'  <metadata key="printer_model_id" value="{model_id}"/>\n'
            '  <metadata key="nozzle_diameters" value="0.4"/>\n'
            f"{rows} </plate>\n</config>\n")


def orca_export(path, inner, **info_kw):
    """A zip in the layout the Orca CLI sliced export writes, around `inner` (bytes)."""
    entries = {
        "[Content_Types].xml": b"<Types/>",
        "_rels/.rels": b"<Relationships/>",
        "3D/3dmodel.model": b"<model/>",
        "Metadata/plate_1.gcode": inner,
        "Metadata/plate_1.gcode.md5": hashlib.md5(inner).hexdigest().upper().encode(),
        "Metadata/slice_info.config": slice_info(**info_kw).encode(),
        "Metadata/plate_1.json": json.dumps(
            {"bbox_all": [10.0, 10.0, 120.0, 120.0],
             "bbox_objects": [{"name": "Part", "bbox": [10.0, 10.0, 120.0, 120.0]}]}).encode(),
        "Metadata/plate_1.png": _png((200, 30, 30)),
        "Metadata/plate_1_small.png": _png((30, 30, 200)),
    }
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in entries.items():
            archive.writestr(name, data)
    return Path(path)


def ad5x():
    config = copy.deepcopy(settings.load(local=False, environ={}))
    return printers.MODELS["flashforge.ad5x"], printers.get("flashforge.ad5x", config)


def rewrite_entry(package, name, data):
    with zipfile.ZipFile(package) as archive:
        entries = {info.filename: archive.read(info.filename) for info in archive.infolist()}
    entries[name] = data
    with zipfile.ZipFile(package, "w", zipfile.ZIP_DEFLATED) as archive:
        for key, value in entries.items():
            archive.writestr(key, value)


# ----------------------------------------------------------------------------- repack

def test_repack_binds_the_finalized_bytes_and_refreshes_the_md5(tmp_path):
    package = orca_export(tmp_path / "plate_1.gcode.3mf", RAW.encode())
    gcode = tmp_path / "plate_1.gcode"
    final = finalized()
    gcode.write_bytes(final.encode())

    delivery.repack_zmod_package(package, gcode, printer_model_id="AD5X")

    assert delivery.extract_zmod_plate_gcode(package) == final.encode()
    with zipfile.ZipFile(package) as archive:
        assert archive.read("Metadata/plate_1.gcode.md5") == \
            hashlib.md5(final.encode()).hexdigest().upper().encode()
        info = archive.read("Metadata/slice_info.config").decode()
        plate_json = archive.read("Metadata/plate_1.json")
    assert 'key="printer_model_id" value="AD5X"' in info
    assert json.loads(plate_json)["bbox_all"] == [10.0, 10.0, 120.0, 120.0]  # carried over untouched
    model, adapter = ad5x()
    assert delivery.zmod_package_problems(package, model, adapter) == []


def test_repack_refuses_a_package_without_exactly_one_plate(tmp_path):
    package = orca_export(tmp_path / "plate_1.gcode.3mf", RAW.encode())
    with zipfile.ZipFile(package, "a") as archive:
        archive.writestr("Metadata/plate_2.gcode", b"G1 X1\n")
    gcode = tmp_path / "plate_1.gcode"
    gcode.write_bytes(RAW.encode())
    with pytest.raises(delivery.DeliveryRefused, match="exactly one sliced plate"):
        delivery.repack_zmod_package(package, gcode)


def test_repack_refuses_a_package_without_slice_info(tmp_path):
    package = orca_export(tmp_path / "plate_1.gcode.3mf", RAW.encode())
    rewrite_entry(package, "Metadata/slice_info.config", b"")
    # an emptied entry is unreadable as the filament source either way; drop it entirely instead
    with zipfile.ZipFile(package) as archive:
        entries = {i.filename: archive.read(i.filename) for i in archive.infolist()
                   if i.filename != "Metadata/slice_info.config"}
    with zipfile.ZipFile(package, "w") as archive:
        for key, value in entries.items():
            archive.writestr(key, value)
    gcode = tmp_path / "plate_1.gcode"
    gcode.write_bytes(RAW.encode())
    with pytest.raises(delivery.DeliveryRefused, match="slice_info"):
        delivery.repack_zmod_package(package, gcode)


# ----------------------------------------------------------------------------- contract

def _plate_xml(package):
    import xml.etree.ElementTree as ET
    with zipfile.ZipFile(package) as archive:
        root = ET.fromstring(archive.read("Metadata/slice_info.config"))
    return next(root.iter("plate"))


def test_package_contract_matches_what_zmods_readers_read(tmp_path):
    """The fields ghzserg's ThreeMFParser / get_colors extract, asserted the same way."""
    package = orca_export(tmp_path / "plate_1.gcode.3mf", RAW.encode())
    gcode = tmp_path / "plate_1.gcode"
    gcode.write_bytes(finalized().encode())
    delivery.repack_zmod_package(package, gcode, printer_model_id="AD5X")

    with zipfile.ZipFile(package) as archive:
        names = archive.namelist()
        plates = [n for n in names if n.startswith("Metadata/plate_") and n.endswith(".gcode")]
        assert plates == ["Metadata/plate_1.gcode"]  # one sliced plate, found by name
        assert "Metadata/plate_1.png" in names and "Metadata/plate_1_small.png" in names
    plate = _plate_xml(package)
    meta = {m.get("key"): m.get("value") for m in plate.findall("metadata")}
    assert meta["index"] == "1"
    assert float(meta["prediction"]) == 3723.0
    assert float(meta["weight"]) == 12.34
    assert meta["printer_model_id"] == "AD5X"
    assert float(meta["nozzle_diameters"].split(",")[0]) == 0.4
    filaments = plate.findall(".//filament")
    # Klipper-side mapping: tool index = filament id - 1, in id order.
    colours = [(int(f.get("id")) - 1, f.get("color"), f.get("type")) for f in filaments]
    assert colours == [(0, "#FF0000", "PLA"), (1, "#0000FF", "PLA")]


