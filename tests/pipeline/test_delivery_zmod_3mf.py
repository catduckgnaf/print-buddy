def test_problems_flag_two_sliced_plates(tmp_path):
    package = orca_export(tmp_path / "plate_1.gcode.3mf", RAW.encode())
    with zipfile.ZipFile(package, "a") as archive:
        archive.writestr("Metadata/plate_2.gcode", b"G1 X1\n")
