def test_layer_progress_gcode_preserves_native_startup_contract():
    machine = json.loads((adapter.TEMPLATES / 'machine.json').read_text())
    start = machine['machine_start_gcode']
    layer = machine['layer_change_gcode']

    assert 'SET_PRINT_STATS_INFO TOTAL_LAYER=[total_layer_count]' in start
    assert 'START_PRINT BED_TEMP=[bed_temperature_initial_layer_single]' in start
    assert ';AFTER_LAYER_CHANGE' in layer and ';[layer_z]' in layer
    assert 'SET_PRINT_STATS_INFO CURRENT_LAYER={layer_num + 1}' in layer
    assert 'TIMELAPSE_TAKE_FRAME' in layer
    rendered = ('M190 S60\nM104 S210 T0\n'
                'START_PRINT BED_TEMP=60 EXTRUDER_TEMP=210 MESH=MESH_DATA\n'
                'SET_PRINT_STATS_INFO TOTAL_LAYER=10\nG90\nG1 X10 Y10 Z0.2\n'
                ';AFTER_LAYER_CHANGE\n;0.2\n'
                'SET_PRINT_STATS_INFO CURRENT_LAYER=1\nTIMELAPSE_TAKE_FRAME\n'
                'END_PRINT\n')
    assert 'START_PRINT BED_TEMP=60 EXTRUDER_TEMP=210 MESH=MESH_DATA' in rendered
    assert job.native_heater_lines_valid(rendered, 60, 210)


def _write_box_3mf(path, width=200.0, depth=100.0, height=10.0):
    vertices = [
        (0, 0, 0), (width, 0, 0), (width, depth, 0), (0, depth, 0),
        (0, 0, height), (width, 0, height), (width, depth, height), (0, depth, height),
    ]
    triangles = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7)]
    xml = ('<?xml version="1.0" encoding="UTF-8"?>'
           '<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">'
           '<resources><object id="1" type="model"><mesh><vertices>'
           + ''.join(f'<vertex x="{x}" y="{y}" z="{z}"/>' for x, y, z in vertices)
           + '</vertices><triangles>'
           + ''.join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in triangles)
           + '</triangles></mesh></object></resources><build><item objectid="1"/></build></model>')
    with zipfile.ZipFile(path, 'w') as archive:
        archive.writestr('3D/3dmodel.model', xml)


def test_scaled_3mf_is_prescaled_and_centered_before_orca(tmp_path):
    source = tmp_path / 'oversized.3mf'
    _write_box_3mf(source)
    observed = {}

    def inspect_slice(cmd, **kwargs):
        observed['cmd'] = cmd
        raw = Path(cmd[-1]).read_bytes()[84:]
        coords = [struct.unpack('<3f', raw[i + offset:i + offset + 12])
                  for i in range(0, len(raw), 50) for offset in (12, 24, 36)]
        observed['bounds'] = tuple((min(row[axis] for row in coords), max(row[axis] for row in coords))
                                   for axis in range(3))
        return fake_slice(cmd, **kwargs)

    with patch.object(adapter.subprocess, 'run', side_effect=inspect_slice):
        _, provenance, _ = adapter.slice_model(source, tmp_path / 'out', state(), scale=0.89)

    assert '--scale' not in observed['cmd']
    assert observed['cmd'][observed['cmd'].index('--arrange') + 1] == '0'
    assert tuple(value for axis in observed['bounds'] for value in axis) == pytest.approx(
        (21.0, 199.0, 65.5, 154.5, 0.0, 8.9))
    assert provenance['geometry']['uniform_scale'] == '0.89'


def test_readiness_selects_native_baseline_not_auto():
    st = state()
    def reply(st, path, **kwargs):
        if path.startswith('/printer/objects/query?bed_mesh'):
            return {'result': {'status': {'bed_mesh': {'profiles': {'auto': {}, 'MESH_DATA': {}}},
                'save_variables': {'variables': {'display_off': 0, 'print_leveling': 0}}}}}
        return {'result': []}
    with patch.object(job, '_mr', side_effect=reply), patch.object(job, 'screen_z_offset', return_value=0.025):
        result = job.mesh_readiness(st)
    assert result['problem'] is None
    assert result['profile'] == 'MESH_DATA'


