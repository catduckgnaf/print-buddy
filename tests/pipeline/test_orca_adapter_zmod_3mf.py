"""[delivery] format gcode_3mf in the Orca step (#564 stage 1).

The fake slicer mimics the pinned OrcaSlicer v2.5.0-alpha CLI: --slice alone writes
plate_1.gcode; --slice with --export-3mf also writes the sliced package (the behaviour
proven against the real binary and ZMod's own 3MF readers in #564). Print Handy's
finalize is stubbed to append a marker line, so the tests can prove the package is
repacked around the finalized bytes, not the slicer's pre-finalize inner copy.
"""
import copy
import zipfile
from pathlib import Path

import pytest

from print_handy import printers, settings
from print_handy.core import delivery
from print_handy.core import orca_adapter as adapter
from .test_delivery_zmod_3mf import orca_export
from .test_orca_adapter import _allow_post, _source, _state

GCODE = "; generated by OrcaSlicer 2.5.0-alpha\nG90\nG1 X1 Y1 Z0.2\nEND_PRINT\n"
MARKER = "; finalized-by-print-handy\n"


def config_3mf(model="flashforge.ad5x"):
    config = copy.deepcopy(settings.load(local=False, environ={}))
    config["delivery"]["format"] = "gcode_3mf"
    return printers.get(model, config)


def fake_run_factory(*, export=True, orca_fails=False):
    """A subprocess.run stand-in: Orca (+ optional export), Bambu fallback."""
    calls = []

    def run(command, **_kwargs):
        calls.append(command)
        folder = Path(command[command.index("--outputdir") + 1])
        folder.mkdir(parents=True, exist_ok=True)
        if "com.orcaslicer.OrcaSlicer" in command:
            if orca_fails:
                return type("R", (), {"returncode": 18, "stdout": "", "stderr": "Orca exploded"})()
            (folder / "plate_1.gcode").write_text(GCODE)
            if export and "--export-3mf" in command:
                # Orca joins the export name onto --outputdir (see orca_adapter).
                target = folder / command[command.index("--export-3mf") + 1]
                orca_export(target, GCODE.encode())
            return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()
        (folder / "plate_1.gcode").write_text(
            "; HEADER_BLOCK_START\n; BambuStudio 2.8.2\n"
            "; model printing time: 1m 0s; total estimated time: 2m 0s\nG90\nG1 X1 Y1 Z0.2\nEND_PRINT\n")
        return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()

    return run, calls


def _finalize_marker(monkeypatch):
    def finalize(path, *_args):
        Path(path).write_bytes(Path(path).read_bytes() + MARKER.encode())
    monkeypatch.setattr(adapter, "finalize_zmod", finalize)


def test_setting_on_exports_repacks_and_records_the_package(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    _finalize_marker(monkeypatch)
    run, calls = fake_run_factory()
    monkeypatch.setattr(adapter.subprocess, "run", run)
    printer = config_3mf()

    output, provenance, _configs = adapter.slice_model(
        _source(tmp_path), tmp_path / "out", _state(), adapter=printer)

    orca = next(c for c in calls if "com.orcaslicer.OrcaSlicer" in c)
    assert orca[orca.index("--export-3mf") + 1] == "plate_1.gcode.3mf"  # bare name, joined to --outputdir
    target = tmp_path / "out" / "plate_1.gcode.3mf"
    assert provenance["delivery_format"] == "gcode_3mf"
    assert provenance["delivery_file"] == str(target)
    # The package's inner G-code is the finalized file, byte for byte, marker included.
    assert delivery.extract_zmod_plate_gcode(target) == output.read_bytes()
    assert MARKER.encode() in output.read_bytes()
    model = printers.MODELS["flashforge.ad5x"]
    assert delivery.zmod_package_problems(target, model, printer) == []


def test_setting_off_never_exports(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    run, calls = fake_run_factory()
    monkeypatch.setattr(adapter.subprocess, "run", run)

    output, provenance, _configs = adapter.slice_model(_source(tmp_path), tmp_path / "out", _state())

    assert all("--export-3mf" not in c for c in calls)
    assert not (tmp_path / "out" / "plate_1.gcode.3mf").exists()
    assert "delivery_format" not in provenance
    assert output.is_file()


def test_setting_on_does_not_export_for_a_non_flashforge_vendor(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    run, calls = fake_run_factory()
    monkeypatch.setattr(adapter.subprocess, "run", run)
    printer = config_3mf("sovol.sv06")

    _output, provenance, _configs = adapter.slice_model(
        _source(tmp_path), tmp_path / "out", _state(), adapter=printer)

    assert all("--export-3mf" not in c for c in calls)
    assert "delivery_format" not in provenance


def test_setting_on_refuses_a_slice_the_fallback_slicer_produced(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    run, _calls = fake_run_factory(orca_fails=True)
    monkeypatch.setattr(adapter.subprocess, "run", run)
    printer = config_3mf()

    with pytest.raises(RuntimeError, match="gcode_3mf.*produced by Bambu Studio"):
        adapter.slice_model(_source(tmp_path), tmp_path / "out", _state(), adapter=printer)


def test_setting_on_refuses_when_orca_writes_no_export(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    run, _calls = fake_run_factory(export=False)
    monkeypatch.setattr(adapter.subprocess, "run", run)
    printer = config_3mf()

    with pytest.raises(RuntimeError, match="no Orca sliced .gcode.3mf export"):
        adapter.slice_model(_source(tmp_path), tmp_path / "out", _state(), adapter=printer)


def test_setting_on_refuses_an_export_that_fails_validation(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    run, calls = fake_run_factory()
    real_run = run

    def sabotaged(command, **kwargs):
        result = real_run(command, **kwargs)
        if "--export-3mf" in command:
            folder = Path(command[command.index("--outputdir") + 1])
            target = folder / command[command.index("--export-3mf") + 1]
            with zipfile.ZipFile(target, "a") as archive:
                archive.writestr("Metadata/plate_2.gcode", b"G1 X1\n")
        return result

    monkeypatch.setattr(adapter.subprocess, "run", sabotaged)
    printer = config_3mf()

    with pytest.raises(RuntimeError, match="exactly one sliced plate"):
        adapter.slice_model(_source(tmp_path), tmp_path / "out", _state(), adapter=printer)
