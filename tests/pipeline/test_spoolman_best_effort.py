"""#387: Spoolman must never block slicing or a print.

#235 made printer_state.check() warnings-only, but paths escaped it: the
print-start active-spool sync in model_job raised on a Spoolman lookup
failure and refused the launch, the slice-time derived-plate cross-check
did its own raw urlopen, and every other Spoolman call site had its own
transport and its own failure behaviour. These tests pin the replacement
(the real-socket client behaviour lives in tests/core/test_spoolman_client.py;
here the socket itself is faked at the urlopen seam, the #235 pattern, while
the wrapper's real error handling, logging and notice run):

- slicing succeeds and produces G-code with Spoolman refused, timing out
  or answering 500, on the slot/filament data already on hand, with a
  WARNING in the log and exactly one user line:
  the #390 notice (UNAVAILABLE_NOTICE: what failed, that the print
  continues, and what to check);
- print start and completion with Spoolman down raise nothing, and the
  usage that could not be reported is recorded as pending in the job /
  completion record for later reconciliation.
"""
import copy
import json
import logging
import urllib.error
import urllib.request
import zipfile
from pathlib import Path
from unittest import mock
from unittest.mock import patch

import pytest

from print_buddy import settings
from print_buddy.core import model_job, orca_adapter, spoolman_client
from print_buddy.hermes import moonraker_discord_announcements as watcher
from print_buddy.hermes import print_records

DEAD = "http://127.0.0.1:9"  # nothing ever connects: urlopen is faked below


@pytest.fixture(autouse=True)
def _fresh_notice():
    spoolman_client.reset_notice()
    yield
    spoolman_client.reset_notice()


def urlopen_raising(exc):
    """A urlopen stand-in that fails the way a dead Spoolman does."""
    def fake(req, *args, **kwargs):
        raise exc
    return fake


REFUSED = urllib.error.URLError(OSError(111, "Connection refused"))
HTTP_500 = urllib.error.HTTPError(DEAD, 500, "Internal Server Error", {}, None)
TIMED_OUT = urllib.error.URLError(TimeoutError("timed out"))


def use_spoolman_url(monkeypatch, url):
    """Point settings' services.spoolman_url at `url` (the resolver's first source)."""
    config = settings.load(local=False, environ={})
    merged = {**config, "services": {**(config.get("services") or {}), "spoolman_url": url}}
    monkeypatch.setattr(settings, "current", lambda: merged)
    return merged


# --------------------------------------------------------------------- slicing

def _derived_state():
    st = copy.deepcopy(model_job.printer_state.load())
    st["spool"] = {"spoolman_id": 12, "name": "Dark Green PLA", "material": "PLA",
                   "diameter_mm": 1.75, "density": 1.24}
    return st


def _fake_slice(cmd, **kwargs):
    folder = Path(cmd[cmd.index("--outputdir") + 1])
    (folder / "plate_1.gcode").write_text(
        "; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.4.2\n"
        "; filament_type = PLA+\n; HEADER_BLOCK_END\nT0\nG90\n")
    return type("Result", (), {"returncode": 0, "stdout": "", "stderr": ""})()


def _derived_source(tmp_path):
    source = tmp_path / "part.3mf"
    with zipfile.ZipFile(source, "w") as archive:
        archive.writestr("Metadata/project_settings.config", '{\n  "filament_colour": [\n    "#FFFFFF"\n  ]\n}\n')
        archive.writestr("3D/3dmodel.model", "<model/>")
    return source


def _slice_derived(tmp_path, st):
    with patch.object(orca_adapter.subprocess, "run", side_effect=_fake_slice):
        return orca_adapter.slice_model(_derived_source(tmp_path), tmp_path / "out", st,
                                        preserve_layout=True, filament_slot=2)


def test_slice_succeeds_with_spoolman_connection_refused(tmp_path, monkeypatch, capsys):
    use_spoolman_url(monkeypatch, DEAD)
    monkeypatch.setattr(urllib.request, "urlopen", urlopen_raising(REFUSED))
    output, _, _ = _slice_derived(tmp_path, _derived_state())
    assert output.exists()  # G-code produced
    filament = json.loads((tmp_path / "out/filament.json").read_text())
    assert filament["filament_type"] == ["PLA"]  # the slot record's material
    assert capsys.readouterr().out.count(spoolman_client.UNAVAILABLE_NOTICE) == 1


def test_slice_succeeds_with_spoolman_500_warning_logged_and_notice(tmp_path, monkeypatch, capsys, caplog):
    use_spoolman_url(monkeypatch, DEAD)
    monkeypatch.setattr(urllib.request, "urlopen", urlopen_raising(HTTP_500))
    with caplog.at_level(logging.WARNING, logger="print_buddy.core.spoolman_client"):
        output, _, _ = _slice_derived(tmp_path, _derived_state())
    assert output.exists()
    assert any("Spoolman GET /api/v1/spool/" in rec.message and "failed" in rec.message
               for rec in caplog.records)
    assert capsys.readouterr().out.count(spoolman_client.UNAVAILABLE_NOTICE) == 1


def test_slice_succeeds_with_spoolman_timeout(tmp_path, monkeypatch, capsys):
    use_spoolman_url(monkeypatch, DEAD)
    monkeypatch.setattr(urllib.request, "urlopen", urlopen_raising(TIMED_OUT))
    output, _, _ = _slice_derived(tmp_path, _derived_state())
    assert output.exists()
    assert capsys.readouterr().out.count(spoolman_client.UNAVAILABLE_NOTICE) == 1


# --------------------------------------------------------------------- print start

def _sync_state():
    st = copy.deepcopy(model_job.printer_state.load())
    for slot in st["ifs_slots"].values():
        slot["physical_color_verified"] = True
    return st


def _mr_transport(active, *, fail_write=False):
    calls = []

    def reply(st, path, data=None, **kwargs):
        calls.append((path, data))
        assert path == "/server/spoolman/spool_id"
        if data is not None:
            if fail_write:
                raise OSError("Moonraker spoolman proxy unavailable")
            active[0] = data["spool_id"]
        return {"result": {"spool_id": active[0]}}

    return reply, calls


def test_print_start_with_spoolman_down_proceeds_and_records_pending(monkeypatch, capsys):
    st = _sync_state()
    use_spoolman_url(monkeypatch, DEAD)
    monkeypatch.setattr(urllib.request, "urlopen", urlopen_raising(REFUSED))
    active = [10]
    reply, calls = _mr_transport(active)
    saved = {}
    with mock.patch.object(model_job, "_mr", side_effect=reply), \
         mock.patch.object(model_job.printer_state, "load", return_value=_sync_state()), \
         mock.patch.object(model_job.printer_state, "save", side_effect=lambda fresh: saved.update(fresh)):
        result = model_job._sync_active_spool(st, 2)  # must not raise
    assert result["spoolman_pending"] is True
    assert active[0] == 11  # the Moonraker accounting pointer still moved
    assert ("/server/spoolman/spool_id", {"spool_id": 11}) in calls
    assert saved["spool"]["spoolman_id"] == 11
    assert saved["spool"]["material"] == st["ifs_slots"]["2"]["material"]  # slot record, not Spoolman
    assert capsys.readouterr().out.count(spoolman_client.UNAVAILABLE_NOTICE) == 1


def test_print_start_with_spool_pointer_write_down_proceeds_pending(monkeypatch):
    st = _sync_state()
    spool = {"archived": False, "filament": {"material": "PLA", "name": "Pink PLA"}}
    active = [10]
    reply, _calls = _mr_transport(active, fail_write=True)
    with mock.patch.object(model_job, "_mr", side_effect=reply), \
         mock.patch.object(model_job.spoolman_client, "get_spool", return_value=spool), \
         mock.patch.object(model_job.printer_state, "load", return_value=_sync_state()), \
         mock.patch.object(model_job.printer_state, "save"):
        result = model_job._sync_active_spool(st, 2)  # must not raise
    assert result["spoolman_pending"] is True
    assert result["spool_id"] == 11


# --------------------------------------------------------------------- completion

def test_completion_active_spool_marks_unavailable_without_raising(monkeypatch):
    monkeypatch.setattr(watcher, "SPOOLMAN_BASE", DEAD)
    monkeypatch.setattr(watcher, "get_json", lambda path: {"result": {"spool_id": 7}})
    monkeypatch.setattr(urllib.request, "urlopen", urlopen_raising(REFUSED))
    spool = watcher.get_active_spool()  # must not raise
    assert spool["spool_id"] == 7
    assert spool["spoolman_unavailable"] is True


def test_completion_record_carries_pending_usage():
    data = print_records.build_record_data(
        "job.gcode",
        stats={"state": "complete", "print_duration": 30, "filament_used": 1200},
        active_spool={"id": 7, "spoolman_unavailable": True,
                      "filament": {"name": "Black PLA", "material": "PLA"}},
    )
    assert data["spoolman_spool_id"] == 7
    assert data["spoolman_usage_pending"] is True
    settled = print_records.build_record_data(
        "job.gcode",
        stats={"state": "complete", "print_duration": 30, "filament_used": 1200},
        active_spool={"id": 7, "filament": {"name": "Black PLA", "material": "PLA"}},
    )
    assert settled["spoolman_usage_pending"] is None


def test_record_completion_with_spoolman_down_writes_pending_record(monkeypatch, tmp_path):
    monkeypatch.setattr(print_records, "PRINTS_DIR", tmp_path / "Prints")
    monkeypatch.setattr(watcher, "SPOOLMAN_BASE", DEAD)
    monkeypatch.setattr(watcher, "get_json", lambda path: {"result": {"spool_id": 7}})
    monkeypatch.setattr(watcher, "get_file_metadata", lambda filename: {})
    monkeypatch.setattr(watcher, "load_context", lambda job_key: {})
    monkeypatch.setattr(urllib.request, "urlopen", urlopen_raising(REFUSED))
    result = watcher.record_completion("job.gcode", "job.gcode",
                                       {"state": "complete", "print_duration": 30})  # must not raise
    text = Path(result["record_path"]).read_text()
    assert '"spoolman_usage_pending": true' in text
