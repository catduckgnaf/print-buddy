def test_post_slice_holds_only_the_toolpath_to_the_bed():
    text = a1_gcode()
    a = adapter_for(A1)
    bed = capabilities.A1["bed_mm"].value
    r = slice_guard.post_slice(text, tool_slots={0: 1}, ifs_slots=1, bed=bed, templates=a.templates_dir(),
                               envelope=a.motion_envelope_mm)
    assert r.status == "ok", r.as_dict()
    # Without the envelope the vendor wiper park (X-48.2) is an off-bed move, as for every other printer.
    r = slice_guard.post_slice(text, tool_slots={0: 1}, ifs_slots=1, bed=bed, templates=a.templates_dir())
    assert any("off the 256x256 mm bed at X-" in b for b in r.blocked)
    r = slice_guard.post_slice(text.replace("; MACHINE_START_GCODE_END", ""), tool_slots={0: 1}, ifs_slots=1,
                               bed=bed, templates=a.templates_dir(), envelope=a.motion_envelope_mm)
    assert any("no Orca machine start/end markers" in b for b in r.blocked)


# ------------------------------------------------------------------ slicing path with a fake Orca

def fake_slice(tmp_path, monkeypatch, gcode, adapter=None, source=CUBE):
    calls = []

    def run(command, **_kwargs):
        calls.append(list(command))
        out = Path(command[command.index("--outputdir") + 1]) / "plate_1.gcode"
        out.write_text(gcode)
        return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()

    monkeypatch.setattr(orca_adapter.subprocess, "run", run)
    folder = tmp_path / "slice"
    out, provenance, configs = orca_adapter.slice_model(source, folder, state(), adapter=adapter or adapter_for(A1))
    return out, provenance, folder, calls


def test_slice_uses_the_vendor_profile_unchanged(tmp_path, monkeypatch):
    out, provenance, folder, calls = fake_slice(tmp_path, monkeypatch, a1_gcode())
    machine = json.loads((folder / "machine.json").read_text())
    assert machine["machine_start_gcode"] == template(A1)["machine_start_gcode"]
    assert machine["machine_end_gcode"] == template(A1)["machine_end_gcode"]
    assert machine["nozzle_type"] == "stainless_steel" and machine["z_hop_types"] == ["Normal Lift"]
    filament = json.loads((folder / "filament.json").read_text())
    assert filament["nozzle_temperature"] == ["210"] and filament["textured_plate_temp"] == ["60"]
    assert f"{folder / 'machine.json'};{folder / 'process.json'}" in calls[0]  # Orca reads the checked per-job copies
    assert provenance["slice_guard"]["status"] in ("ok", "warnings")
    assert provenance["geometry"]["source_sha256"] == orca_adapter.digest(CUBE)  # original geometry untouched
    assert out.read_text() == a1_gcode()


