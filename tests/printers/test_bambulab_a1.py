def _box(path, w, d, h):
    v = [(x, y, z) for x in (0, w) for y in (0, d) for z in (0, h)]
    faces = [(0, 2, 3), (0, 3, 1), (4, 5, 7), (4, 7, 6), (0, 1, 5), (0, 5, 4),
             (2, 6, 7), (2, 7, 3), (0, 4, 6), (0, 6, 2), (1, 3, 7), (1, 7, 5)]
    lines = ["solid box"]
    for a, b, c in faces:
        lines += ["facet normal 0 0 0", " outer loop", *(f"  vertex {v[i][0]} {v[i][1]} {v[i][2]}" for i in (a, b, c)),
                  " endloop", "endfacet"]
    path.write_text("\n".join(lines + ["endsolid box"]) + "\n")
    return path


def test_exported_geometry_is_centred_on_the_target_bed(tmp_path):
    stl = _box(tmp_path / "box.stl", 240, 240, 10)
    on_220 = orca_adapter.place_stl(stl, tmp_path / "a.stl", bed=(220, 220))["placed_bounds_mm"]
    on_256 = orca_adapter.place_stl(stl, tmp_path / "b.stl", bed=(256, 256))["placed_bounds_mm"]
    assert [list(b) for b in on_220[:2]] == [[-10.0, 230.0], [-10.0, 230.0]]  # 220 mm bed: centre 110, as before
    assert [list(b) for b in on_256[:2]] == [[8.0, 248.0], [8.0, 248.0]]      # 256 mm bed: centre 128, on the bed
    default = orca_adapter.place_stl(stl, tmp_path / "c.stl")["placed_bounds_mm"]
    assert default[0][0] + default[0][1] == 2 * (orca_adapter.BED[0] / 2)  # no bed: the configured printer's


