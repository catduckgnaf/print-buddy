def test_fit_check_uses_the_a1_volume():
    identity = (1, 0, 0, 0, 1, 0, 0, 0, 1)

    def box(w, d, h):
        return [(x, y, z) for x in (0, w) for y in (0, d) for z in (0, h)]

    st = state()
    assert orca_adapter._usable(st) == (254.0, 254.0, 256.0)  # 256 mm bed less the 1 mm single-copy edge
    assert orca_adapter._orientation_bound(box(250, 250, 250), st, identity)[0] == 1.0
    assert orca_adapter._orientation_bound(box(300, 300, 10), st, identity)[0] == pytest.approx(254 / 300)
    assert orca_adapter._orientation_bound(box(100, 100, 260), st, identity)[0] == pytest.approx(256 / 260)
    # The same 250 mm box does not fit an AD5X record: the fit follows the hardware record, not a constant.
    assert orca_adapter._orientation_bound(box(250, 250, 250), {**st, "bed_mm": [220, 220]}, identity)[0] < 1


